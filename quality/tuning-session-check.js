const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const window = { MusicVocal: {} };
vm.runInNewContext(fs.readFileSync('vocal-pitch/tuning-session.js', 'utf8'), { window });
const session = new window.MusicVocal.TuningSession(['E2', 'A2', 'E2'], 'guitar');
const add = (at, cents, stable = false, extra = {}) => session.add({ note: 'E2', instrument: 'guitar', at, cents, stable, ...extra });
assert.equal(add(0, -20), true);
assert.equal(add(100, -20), false);
assert.equal(add(200, 20), true);
assert.equal(add(400, 0, true), true);
assert.equal(session.completed(), 1);
assert.equal(add(600, 2, true, { instrument: 'erhu' }), false);
assert.equal(add(600, 2, true, { note: 'D2' }), false);
assert.equal(add(600, NaN), false);
assert.equal(add(600, 201), false);
assert.equal(add(0, 0), false);
const row = session.summary()[0];
assert.equal(row.samples, 3); assert.equal(row.lowCount, 1); assert.equal(row.highCount, 1); assert.equal(row.stableCount, 1); assert.equal(row.meanCents, 0);
assert.equal(session.summary().length, 2);
assert.equal(session.summary()[1].samples, 0);
const transient = new window.MusicVocal.TuningSession(['E2'], 'guitar');
transient.add({ note: 'E2', instrument: 'guitar', at: 0, cents: 0, stable: true });
assert.equal(transient.completed(), 0);
for (let i = 1; i < 4000; i++) transient.add({ note: 'E2', instrument: 'guitar', at: i * 200, cents: 10, stable: false });
assert.equal(transient.summary()[0].samples, 3600);
console.log('PASS target/instrument isolation, throttling, stable completion, summary counts and bounded session');
