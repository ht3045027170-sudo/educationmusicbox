import assert from 'node:assert/strict';
import { answersEqual, validAnswer, validQuestionAnswer, gradeHomework, assignmentSections } from '../functions/api/homework-grading.js';
assert(!answersEqual('', ''));
assert(!answersEqual('', undefined));
assert(!validAnswer(['']));
assert(!validAnswer(['A',' a ']));
assert(!validAnswer({ answer: 'A' }));
assert(answersEqual([' B ', 'a'], ['A','B']));
assert(!answersEqual(['A','A'], ['A','B']));
assert(!answersEqual('A|B', ['A','B']));
assert(answersEqual(0, '0'));
const contents = new Map([[1,{answer:'A'}],[2,{answer:['C','B']}]]);
const sections = [{ questions:[{questionId:1,score:2},{questionId:2,score:8}] }];
let result = gradeHomework([1,2], contents, {1:'A',2:['B','C']},sections);
assert.equal(result.score,100); assert.deepEqual(result.gradedAnswers[2],['B','C']);
result = gradeHomework([1,2],contents,{1:'A'},sections);
assert.equal(result.score,20); assert.equal(result.correct,1); assert.equal(result.possible,10);
assert.equal(gradeHomework([1,2],contents,{1:'A'}).score,50,'legacy assignments keep equal weights');
assert.throws(()=>gradeHomework([1,3],contents,{}),/标准答案/);
assert.throws(()=>gradeHomework([1,2],contents,{},[{questions:[{questionId:1,score:2}]}]),/不一致/);
for(const score of [NaN,-1,Infinity]) assert.throws(()=>gradeHomework([1],contents,{},[{questions:[{questionId:1,score}]}]),/分值/);
assert.throws(()=>gradeHomework([1],contents,{},[{questions:[{questionId:1,score:0}]}]),/总分/);
const calls=[];
const env={DB:{prepare(sql){calls.push(sql);return{bind(){return{async first(){return {sections_json:JSON.stringify(sections)}}}}}}}};
assert.deepEqual(await assignmentSections(env,{id:1,question_set_id:4}),sections);
assert.equal(calls.length,1,'snapshot takes precedence over edited source set');
console.log('PASS weighted and legacy scoring, multi-select, blanks, missing questions, invalid weights, publication snapshot');

assert(validQuestionAnswer({options:['A','B'],answer:'A'},'single_choice'));
assert(!validQuestionAnswer({options:['A','B'],answer:'C'},'single_choice'));
assert(!validQuestionAnswer({options:['A',' a '],answer:'A'},'single_choice'));
assert(!validQuestionAnswer({options:[],answer:'A'},'single_choice'));
assert(!validQuestionAnswer({options:['A','B'],answer:['A']},'single_choice'));
assert(validQuestionAnswer({options:['A','B','C'],answer:['B','A']},'multi_choice'));
assert(!validQuestionAnswer({options:['A','B'],answer:['A','C']},'multi_choice'));
assert(validQuestionAnswer({answer:'旋律答案'},'text_input'));
const oneNine=[{questions:[{questionId:1,score:1},{questionId:2,score:9}]}];
assert.equal(gradeHomework([1,2],contents,{1:'A'},oneNine).score,10);
assert.equal(gradeHomework([1,2],contents,{2:['B','C']},oneNine).score,90);
